import { _electron as electron, expect as baseExpect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { authLauncher } from '../tests/fixtures/auth-launcher.mjs';
import { setConnectionProfile } from './connection-helpers.mjs';
const expect = baseExpect.configure({ timeout: 15000 });
const root = process.cwd(), data = path.join(root, '.test-data', 'connection-setup-' + Date.now());
const store = path.join(data, 'user'), workspace = path.join(data, 'work'), share = path.join(data, 'admin-share');
await Promise.all([store, workspace, share].map(dir => fs.mkdir(dir, { recursive: true })));
const cli = await authLauncher(path.join(data, 'cli'));
await fs.writeFile(path.join(store, 'settings.json'), JSON.stringify({ connections: [], providerPaths: { codex: cli.launcher, cursor: cli.launcher }, lastWorkspace: '' }));
const alice = { id: 'alice', mode: 'local', name: 'competition.xxx', host: 'local', port: 22, username: 'alice', localRoot: share, fingerprint: 'local', projects: [], workPath: '', manifestPath: '' };
const bob = { ...alice, id: 'bob', username: 'bob', name: 'competition.bob' };
const ssh = { ...alice, id: 'ssh', mode: 'sftp', localRoot: undefined, host: 'team.example.test', username: 'alice', name: '研发团队', fingerprint: 'SHA256:test' };
const profiles = { alice, bob, ssh, incomplete: { ...alice, localRoot: undefined } };
const env = { ...process.env, WORKBENCH_TEST: '1', WORKBENCH_DATA_DIR: store }; delete env.ELECTRON_RUN_AS_NODE;
const errors = []; let app, page;
async function launch() {
  app = await electron.launch({ args: ['dist/user'], cwd: root, env, timeout: 60000 });
  page = await app.firstWindow(); page.on('pageerror', e => errors.push(e.message));
}
try {
  await launch();
  await expect(page.getByLabel('本地共享区根目录', { exact: true })).toHaveCount(0);
  await expect(page.getByLabel('团队连接（已保存）')).toHaveCount(0);
  await expect(page.getByRole('button', { name: '登录', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: '导入团队连接配置' })).toHaveCount(0);
  await expect(page.getByRole('button', { name: '手动设置 SSH 连接' })).toHaveCount(0);
  await expect(page.getByRole('button', { name: '添加其他服务器', exact: true })).toHaveCount(0);
  await expect(page.getByLabel('服务器地址', { exact: true })).toBeVisible();
  await expect(page.locator('.connection-server-details')).toBeVisible();
  await expect(page.getByLabel('服务器身份状态')).toHaveCount(0);
  await expect(page.getByText('查看技术信息', { exact: true })).toHaveCount(0);
  await page.screenshot({ path: path.join(data, 'first-start.png') });
  await setConnectionProfile({ app, page }, profiles.alice);
  await expect(page.getByLabel('团队连接（已保存）')).toHaveCount(0);
  await expect(page.getByText('competition.xxx', { exact: true })).toHaveCount(0);
  await expect(page.getByLabel('连接名称', { exact: true })).toHaveCount(0);
  await expect(page.getByText('共享空间由账号权限决定', { exact: true })).toHaveCount(0);
  await expect(page.getByText('代码和个人工作文件所在的本机目录。这里只需要选择这一处路径。', { exact: true })).toHaveCount(0);
  await expect(page.locator('.workspace-discovery-note')).toHaveCount(0);
  await page.getByLabel('登录密码', { exact: true }).fill('not-persisted');
  await expect(page.getByRole('button', { name: '登录', exact: true })).toBeDisabled();
  await app.evaluate(({ dialog }, directory) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] }); }, workspace);
  await page.getByRole('button', { name: '选择目录', exact: true }).click();
  await expect(page.getByLabel('本机工作路径', { exact: true })).toHaveValue(workspace);
  await expect(page.getByRole('button', { name: '登录', exact: true })).toBeEnabled();
  assert.equal((await page.evaluate(() => window.workbench.call('snapshot'))).settings.connections[0].localRoot, share);
  await page.setViewportSize({ width: 1100, height: 760 });
  await page.getByLabel('登录密码', { exact: true }).fill('');
  await page.screenshot({ path: path.join(data, 'single-connection.png') });
  await page.getByLabel('登录密码', { exact: true }).fill('not-persisted');
  await setConnectionProfile({ app, page }, profiles.bob);
  await expect(page.getByLabel('成员账号')).toHaveValue('bob');
  await expect(page.getByLabel('登录密码', { exact: true })).toHaveValue('');
  await expect(page.getByLabel('团队连接（已保存）')).toHaveCount(0);
  await page.getByLabel('成员账号').fill('alice');
  await expect(page.getByLabel('成员账号')).toHaveValue('alice');
  await expect(page.getByLabel('本机工作路径', { exact: true })).toHaveValue('');
  await page.getByLabel('本机工作路径', { exact: true }).fill(workspace);
  await page.screenshot({ path: path.join(data, 'multiple-connections.png') });
  await setConnectionProfile({ app, page }, profiles.incomplete);
  await expect(page.getByRole('alert')).toContainText('本地测试连接缺少共享目录');
  await page.getByLabel('登录密码', { exact: true }).fill('not-persisted');
  await expect(page.getByRole('button', { name: '登录', exact: true })).toBeDisabled();
  await setConnectionProfile({ app, page }, profiles.alice);
  await expect(page.getByRole('alert')).toHaveCount(0);
  await setConnectionProfile({ app, page }, profiles.ssh);
  await expect(page.getByLabel('服务器地址', { exact: true })).toBeVisible();
  await expect(page.getByLabel('服务器地址', { exact: true })).toHaveValue('team.example.test');
  await expect(page.getByLabel('服务器身份状态')).toHaveCount(0);
  await expect(page.getByText('查看技术信息', { exact: true })).toHaveCount(0);
  await expect(page.getByText('SHA256:test', { exact: true })).toHaveCount(0);
  await expect(page.getByLabel('管理员提供的服务器指纹')).toHaveCount(0);
  await expect(page.getByRole('button', { name: '重新确认', exact: true })).toHaveCount(0);
  await page.getByLabel('服务器地址', { exact: true }).fill('new.example.test');
  await expect(page.getByLabel('服务器地址', { exact: true })).toHaveValue('new.example.test');
  await expect(page.getByRole('button', { name: '添加其他服务器', exact: true })).toHaveCount(0);
  await expect(page.getByLabel('团队连接（已保存）')).toHaveCount(0);
  await app.close(); await launch();
  await expect(page.getByLabel('团队连接（已保存）')).toHaveCount(0);
  await expect(page.getByLabel('服务器地址', { exact: true })).toHaveValue('team.example.test');
  await expect(page.getByLabel('登录密码', { exact: true })).toHaveValue('');
  const settings = await fs.readFile(path.join(store, 'settings.json'), 'utf8');
  assert(!settings.includes('not-persisted')); assert(!settings.includes('new.example.test'));
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, data, cases: ['fresh start shows a direct login form', 'local fixture hides shared root', 'only local work path chosen', 'legacy multiple profiles never add a connection selector', 'server and account change in the same form', 'incomplete local fixture is rejected', 'server identity details stay hidden', 'restart retains the saved server, never password or unsaved edits'] }));
} catch (e) {
  await page?.screenshot({ path: path.join(data, 'failure.png') }).catch(() => {}); throw e;
} finally { await app?.close().catch(() => {}); }
