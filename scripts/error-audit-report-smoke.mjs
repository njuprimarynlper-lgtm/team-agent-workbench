import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { chromium } from '@playwright/test';

const directory = path.resolve('docs/error-audit');
const data = JSON.parse(await fs.readFile(path.join(directory, 'report-data.json'), 'utf8'));
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [], externalRequests = [], checks = [];
page.on('pageerror', error => errors.push(error.message));
await page.route(/^https?:/, route => { externalRequests.push(route.request().url()); return route.abort(); });
const url = pathToFileURL(path.join(directory, '报错整改报告.html')).href;
try {
  await page.goto(url);
  assert.equal(await page.locator('article.card').count(), data.scenes.length);
  checks.push('离线打开，全部场景可读');
  await page.getByLabel('搜索报告').fill('u46');
  assert.equal(await page.locator('article.card').count(), 1);
  assert.equal(await page.locator('article.card').first().getAttribute('id'), 'u46');
  await page.getByLabel('搜索报告').fill('');
  await page.getByLabel('筛选模块').selectOption('logs');
  assert.equal(await page.locator('article.card').count(), data.scenes.filter(row => row.domain === 'logs').length);
  checks.push('搜索与模块筛选');
  await page.getByLabel('筛选模块').selectOption('');
  await page.getByLabel('筛选验收状态').selectOption('pending');
  assert.equal(await page.locator('article.card').count(), data.scenes.filter(row => !row.reviewCurrent).length);
  await page.getByLabel('筛选验收状态').selectOption('low');
  assert.equal(await page.locator('article.card').count(), data.scenes.filter(row => !row.notApplicable && (!row.review || row.review.score < 9)).length);
  await page.getByLabel('筛选验收状态').selectOption('');
  await page.getByLabel('筛选模块').selectOption('logs');
  checks.push('逐项 9 分门禁筛选，不以平均分代替放行');
  const image = page.locator('article.card img').first();
  await image.scrollIntoViewIfNeeded(); await image.click();
  assert(await page.locator('#imageDialog').isVisible());
  assert(await page.locator('#zoom').evaluate(img => img.complete && img.naturalWidth > 0));
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  assert(!await page.locator('#imageDialog').isVisible());
  checks.push('实际截图可加载、放大与关闭');
  await page.getByLabel('筛选模块').selectOption('');
  await page.getByRole('button', { name: '完整候选清单', exact: true }).click();
  assert.equal(await page.locator('tbody tr').count(), 60);
  const firstCandidate = await page.locator('tbody tr').first().getAttribute('id');
  await page.getByRole('button', { name: '下一页', exact: true }).click();
  assert.notEqual(await page.locator('tbody tr').first().getAttribute('id'), firstCandidate);
  await page.getByLabel('搜索报告').fill(data.candidates[0].id);
  assert.equal(await page.locator('tbody tr').count(), 1);
  checks.push('候选清单有界分页与编号搜索');
  await page.goto(url + '#boundary-password');
  await page.waitForTimeout(250);
  assert(await page.locator('#boundary-password').isVisible());
  const bounds = await page.locator('#boundary-password').boundingBox();
  assert(bounds && bounds.y >= 0 && bounds.y < 350);
  checks.push('场景链接直接跳转');
  await page.setViewportSize({ width: 600, height: 900 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  checks.push('窄窗口无横向溢出');
  assert.deepEqual(errors, []); assert.deepEqual(externalRequests, []);
  checks.push('无页面异常、无外网请求');
  await fs.writeFile(path.join(directory, 'report-smoke-verification.json'), JSON.stringify({ passed: true, checks, scenes: data.scenes.length, generatedAt: new Date().toISOString() }, null, 2));
  console.log(JSON.stringify({ passed: true, checks }));
} finally { await browser.close(); }
