import { _electron as electron, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { adminServer } from '../tests/fixtures/admin-server.mjs';

const data = path.resolve('.test-data', 'server-environment-' + Date.now()); await fs.mkdir(data, { recursive: true });
const server = await adminServer(), errors = [];
server.state.initialized = false;
server.control.missingCommands = ['setfacl'];
server.control.setupIssues = ['缺少 ACL 工具。请在服务器执行：sudo apt-get update && sudo apt-get install -y acl；安装后点击“重新检查服务器”。'];
const env = { ...process.env, WORKBENCH_TEST: '1', WORKBENCH_ADMIN_DATA_DIR: data }; delete env.ELECTRON_RUN_AS_NODE;
let app, page;
try {
  app = await electron.launch({ args: ['dist/admin'], cwd: process.cwd(), env }); page = await app.firstWindow(); page.on('pageerror', error => errors.push(error.message));
  await page.locator('.modal').waitFor();
  await page.evaluate(profile => window.admin.call('connect', { profile, password: 'test-password', sudoPassword: '' }), server.profile);
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await expect(page.getByRole('alert', { name: '服务器环境待完善' })).toContainText('apt-get install -y acl');
  await expect(page.getByRole('alert', { name: '服务器环境待完善' })).toContainText('问题在服务器上，本机 Windows 无需安装');
  await expect(page.getByRole('alert', { name: '服务器环境待完善' })).toContainText(server.profile.host);
  await expect(page.getByRole('button', { name: '初始化团队空间', exact: true })).toBeDisabled();
  await page.screenshot({ path: path.join(data, 'missing-acl.png') });
  server.control.missingCommands = []; server.control.setupIssues = [];
  await page.getByRole('button', { name: '重新检查服务器', exact: true }).click();
  await expect(page.getByRole('button', { name: '初始化团队空间', exact: true })).toBeEnabled();
  await expect(page.getByRole('alert', { name: '服务器环境待完善' })).toHaveCount(0);
  server.state.initialized = true;
  server.control.setupIssues = ['未检测到运行中的 systemd 或可管理的 Supervisor。请配置容器服务管理。'];
  await page.evaluate(() => window.admin.call('operation', { op: 'status' }));
  await expect(page.getByRole('button', { name: '创建用户组', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: '创建用户', exact: true })).toBeDisabled();
  server.control.setupIssues = [];
  await page.getByRole('button', { name: '重新检查服务器', exact: true }).click();
  await expect(page.getByRole('button', { name: '创建用户组', exact: true })).toBeEnabled();
  await expect(page.getByRole('button', { name: '创建用户', exact: true })).toBeEnabled();
  server.control.missingCommands = ['setfacl']; server.control.setupIssues = ['缺少 ACL 支持'];
  await page.evaluate(() => window.admin.call('operation', { op: 'status' }));
  await page.getByRole('button', { name: '查看服务器修复方式', exact: true }).click();
  await page.getByRole('button', { name: '取消', exact: true }).click();
  assert(!server.requests.some(request => request.op === 'environment_prepare'));
  await page.getByRole('button', { name: '查看服务器修复方式', exact: true }).click();
  const preparation = page.getByRole('dialog', { name: '修复远端服务器环境', exact: true });
  await expect(preparation).toContainText('操作位置：');
  await expect(preparation).toContainText(server.profile.host);
  await expect(preparation).toContainText('通过当前 SSH 连接');
  await expect(preparation).toContainText('本机不下载软件包');
  await preparation.getByLabel('服务器安装方式').selectOption('offline');
  await expect(preparation).toContainText('管理端不会从本机上传安装包，也不会联网下载');
  await expect(preparation.getByRole('button', { name: '在服务器执行修复', exact: true })).toBeDisabled();
  await preparation.getByLabel('服务器上的离线包目录').fill('/opt/workbench-packages');
  server.control.failEnvironment = true;
  await preparation.getByRole('button', { name: '在服务器执行修复', exact: true }).click();
  await expect(preparation.getByRole('alert')).toContainText('离线包依赖不完整');
  await page.screenshot({ path: path.join(data, 'offline-retry.png') });
  await preparation.getByRole('button', { name: '在服务器执行修复', exact: true }).click();
  await expect(preparation.getByRole('button', { name: '取消', exact: true })).toBeDisabled();
  await expect(preparation.getByRole('status')).toContainText('远端服务器环境已通过检查');
  await preparation.getByRole('button', { name: '关闭', exact: true }).click();
  await expect(page.getByRole('button', { name: '创建用户', exact: true })).toBeEnabled();
  assert.equal(server.requests.filter(request => request.op === 'environment_prepare' && request.source === 'offline' && request.packageDirectory === '/opt/workbench-packages').length, 2);
  server.control.setupIssues = ['缺少 Supervisor'];
  await page.evaluate(() => window.admin.call('operation', { op: 'status' }));
  await page.getByRole('button', { name: '查看服务器修复方式', exact: true }).click();
  await preparation.getByRole('button', { name: '在服务器执行修复', exact: true }).click();
  await expect(preparation.getByRole('status')).toContainText('远端服务器环境已通过检查');
  await preparation.getByRole('button', { name: '关闭', exact: true }).click();
  assert.equal(server.requests.filter(request => request.op === 'environment_prepare' && request.source === 'online').length, 1);
  assert(server.requests.filter(request => request.op === 'probe').length >= 4);
  assert(!server.requests.some(request => ['initialize', 'user_create', 'group_create'].includes(request.op)));
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, data, cases: ['early ACL guidance', 'initialization blocked before mutation', 'refresh clears repaired prerequisites', 'unsupported manager blocks creation', 'management resumes without reconnecting', 'cancel never installs', 'offline directory required', 'offline failure shown and retry succeeds', 'busy preparation cannot be dismissed', 'online preparation restores management'] }));
} catch (error) { if (page && !page.isClosed()) await page.screenshot({ path: path.join(data, 'failure.png') }).catch(() => {}); throw error; }
finally { await app?.close().catch(() => {}); await server.close(); }
