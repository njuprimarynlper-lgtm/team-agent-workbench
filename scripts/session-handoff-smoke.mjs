import { offlineSettings, offlineProjectId } from '../tests/fixtures/offline-workspace.mjs';
import { _electron as electron, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { authLauncher } from '../tests/fixtures/auth-launcher.mjs';
import { dismissStartupLogin } from './connection-helpers.mjs';

const root = process.cwd();
const data = await fs.mkdtemp(path.join(os.tmpdir(), 'wb-handoff-ui-'));
const work = path.join(data, 'work'); await fs.mkdir(work);
const fixture = await authLauncher(path.join(data, 'cli'), { status: 'ready', turn: 'success' });
await fs.writeFile(path.join(data, 'settings.json'), JSON.stringify({ ...offlineSettings(), connections: [], providerPaths: { codex: fixture.launcher, cursor: fixture.launcher, claude: '' }, lastWorkspace: work, localWorkspace: work, verifiedLocalWorkspace: work }));
const env = { ...process.env, WORKBENCH_TEST: '1', WORKBENCH_DATA_DIR: data }; delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ args: ['dist/user'], cwd: root, env, timeout: 60000 });
try {
  const page = await app.firstWindow();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const call = (action, payload) => page.evaluate(([name, input]) => window.workbench.call(name, input), [action, payload]);
  await dismissStartupLogin(page);
  const projectDialog = page.getByRole('dialog', { name: '设置项目代码目录' });
  if (await projectDialog.isVisible()) await projectDialog.getByRole('button', { name: '暂不设置' }).click();
  const first = await call('session.create', { provider: 'codex', cwd: work, projectId: offlineProjectId, includeBrief: false });
  await call('session.rename', { id: first.id, title: '接口方案' });
  await call('handoff.save', { id: first.id, text: '# 阶段摘要\n\n## 当前进展\n接口方案已确认。\n\n## 下一步\n验证调用方。' });
  const second = await call('session.create', { provider: 'cursor', cwd: work, projectId: offlineProjectId, includeBrief: false });
  await page.locator(`[data-session-id="${second.id}"]`).click();
  await expect(page.getByRole('button', { name: /创建 Subsession/ })).toBeDisabled();
  await expect(page.getByRole('button', { name: '引用会话摘要' })).toHaveCount(0);
  await assert.rejects(call('handoff.list', { id: second.id }), /Beta 功能/);
  await page.getByRole('button', { name: 'Beta 功能' }).click();
  const betaSwitch = page.getByRole('switch', { name: '开启跨会话引用与 Subsession' });
  await expect(betaSwitch).not.toBeChecked();
  await betaSwitch.click();
  await expect(betaSwitch).toBeChecked();
  await page.getByRole('button', { name: '完成' }).click();
  await page.getByRole('button', { name: '引用会话摘要' }).click();
  const dialog = page.getByRole('heading', { name: '引用其他会话的阶段摘要' }).locator('..').locator('..');
  await expect(dialog.getByText('接口方案已确认。')).toBeVisible();
  await dialog.getByRole('button', { name: '加入当前会话' }).click();
  await expect(page.getByLabel('待发送的参考资料')).toContainText('会话摘要 · 接口方案');
  await assert.rejects(call('session.autoUpload', { id: second.id, enabled: true }), /个人会话内容/);
  await page.getByRole('button', { name: '轨迹上传' }).click();
  await expect(page.getByText('轨迹可能含有相关对话内容', { exact: false })).toBeVisible();
  await expect(page.getByLabel('此会话自动上传')).toBeDisabled();
  await page.getByRole('button', { name: '关闭窗口' }).click();
  const before = await call('snapshot');
  assert.equal(before.sessions.find(item => item.id === second.id).messages.length, 0, 'joining a snapshot does not send a model turn');
  assert.equal(before.inputs[second.id].sourceIds.length, 1);
  await page.getByLabel('任务输入').fill('请接着验证调用方');
  await page.getByRole('button', { name: '发送任务' }).click();
  await expect.poll(async () => (await call('snapshot')).sessions.find(item => item.id === second.id)?.messages.some(item => item.role === 'assistant'), { timeout: 25000 }).toBe(true);
  const after = await call('snapshot');
  assert(after.sessions.find(item => item.id === second.id).messages.some(item => item.role === 'user' && item.context?.accepted && Object.keys(item.context.sourceHashes).length === 1));
  const createChild = page.getByRole('button', { name: /创建 Subsession/ });
  await expect(createChild).toBeEnabled(); await createChild.click();
  const forkDialog = page.getByRole('dialog', { name: /创建 Subsession/ });
  await forkDialog.getByRole('textbox', { name: '这条探索要做什么' }).fill('方案 A');
  await forkDialog.getByRole('button', { name: '创建 Subsession' }).click();
  await expect(forkDialog).toHaveCount(0);
  const child = (await call('snapshot')).sessions.find(item => item.fork?.parentId === second.id);
  assert(child); assert.notEqual(child.cwd, second.cwd);
  await call('handoff.save', { id: child.id, text: '# 阶段摘要\n\n方案 A 的验证尚未完成。' });
  await page.getByRole('button', { name: '回报父会话' }).click();
  const reportDialog = page.getByRole('dialog', { name: /回报父会话/ });
  await expect(reportDialog.getByRole('textbox', { name: '子会话回报内容' })).toContainText('方案 A 的验证尚未完成');
  await reportDialog.getByRole('button', { name: '回报父会话' }).click();
  await expect(reportDialog).toHaveCount(0);
  await page.getByRole('button', { name: '返回父会话' }).click();
  await page.locator('.subsession-panel > summary').click();
  await expect(page.locator('.subsession-panel')).toContainText('1 条新回报');
  await page.getByRole('button', { name: '查看回报' }).click();
  const reportDetail = page.getByRole('dialog', { name: /方案 A · 回报 v1/ });
  await expect(reportDetail).toContainText('方案 A 的验证尚未完成');
  await reportDetail.getByRole('button', { name: '加入父会话待发送内容' }).click();
  await expect(page.getByLabel('待发送的参考资料')).toContainText('方案 A · 回报 v1');
  const afterAttach = await call('snapshot');
  assert.equal(afterAttach.sessions.find(item => item.id === second.id).messages.length, after.sessions.find(item => item.id === second.id).messages.length, 'reviewing a report does not send a model turn');
  const childB = await call('subsession.create', { parentId: second.id, focus: '方案 B' });
  await call('handoff.save', { id: childB.id, text: '# 阶段摘要\n\n方案 B 保持原指标，尚需性能验证。' });
  const previewB = await call('subsession.report.preview', { id: childB.id });
  await call('subsession.report.publish', { id: childB.id, sourceHash: previewB.sourceHash, body: previewB.body });
  await page.getByRole('checkbox', { name: '比较回报：方案 A' }).check();
  await page.getByRole('checkbox', { name: '比较回报：方案 B' }).check();
  await page.getByRole('button', { name: '并排比较（2）' }).click();
  const compare = page.getByRole('dialog', { name: '比较子会话回报' });
  await expect(compare).toContainText('方案 A 的验证尚未完成');
  await expect(compare).toContainText('方案 B 保持原指标');
  await compare.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '查看回报' }).first().click();
  await page.getByRole('dialog', { name: /回报 v1/ }).getByRole('button', { name: '要求补充' }).click();
  const followup = page.getByRole('dialog', { name: /要求.*补充/ });
  await followup.getByRole('textbox', { name: '给子会话的补充要求' }).fill('请补测运行时间。');
  await followup.getByRole('button', { name: '转到子会话' }).click();
  await expect(page.getByLabel('任务输入')).toHaveValue('方案 B\n\n请补测运行时间。');
  await page.getByRole('button', { name: '返回父会话' }).click();
  await page.getByRole('button', { name: 'Beta 功能' }).click(); await betaSwitch.uncheck(); await page.getByRole('button', { name: '完成' }).click();
  await expect(page.getByRole('button', { name: /创建 Subsession/ })).toBeDisabled();
  await assert.rejects(call('subsession.create', { parentId: second.id, focus: '方案 C' }), /Beta 功能/);
  assert.deepEqual(errors, []);
} finally { await app.close(); await fs.rm(data, { recursive: true, force: true }); }
